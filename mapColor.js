function getBlockProperties(block) {
  if (!block || typeof block !== "object") return {};
  if (typeof block.getProperties === "function") {
    const p = block.getProperties();
    if (p && typeof p === "object") return p;
  }
  if (block.properties && typeof block.properties === "object") return block.properties;
  if (block.Properties && typeof block.Properties === "object") return block.Properties;
  if (block.state && typeof block.state === "object") {
    if (block.state.properties && typeof block.state.properties === "object") {
      return block.state.properties;
    }
    return block.state;
  }
  return {};
}

function getProperty(properties, name, fallback = undefined) {
  let value = properties?.[name];
  if (value === undefined || value === null) return fallback;
  if (typeof value === "string") {
    const lower = value.toLowerCase();
    if (lower === "true") return true;
    if (lower === "false") return false;
    if (/^-?\d+$/.test(value)) return Number(value);
    return lower;
  }
  return value;
}

/**
 * Return the Minecraft Java Edition 1.21.11 MapColor constant name.
 *
 * Accepted:
 *   mapColor("diamond_block")
 *   mapColor("minecraft:diamond_block")
 *   mapColor({ name: "oak_log", properties: { axis: "x" } })
 *   mapColor(mineflayerBlock)
 */
function mapColor(block) {
  let name;
  let properties = {};

  if (typeof block === "string") {
    name = block;
  } else if (block && typeof block === "object") {
    name = block.name ?? block.Name ?? block.blockName ?? block.id;
    properties = getBlockProperties(block);
  }

  if (typeof name !== "string") {
    throw new TypeError("mapColor(block): block must be a block name or block object");
  }

  name = name.toLowerCase();
  if (name.startsWith("minecraft:")) name = name.slice(10);

  const log = LOG_MAP_COLORS[name];
  if (log) {
    const axis = String(getProperty(properties, "axis", "y")).toLowerCase();
    return axis === "y" ? log[0] : log[1];
  }

  const bed = BED_MAP_COLORS[name];
  if (bed) {
    const part = String(getProperty(properties, "part", "foot")).toLowerCase();
    return part === "foot" ? bed[0] : bed[1];
  }

  if (name === "wheat") {
    const age = Number(getProperty(properties, "age", 0));
    return age >= 6 ? "COLOR_YELLOW" : "PLANT";
  }

  if (name === "barrier" || name === "light") {
    return getProperty(properties, "waterlogged", false) === true ? "WATER" : "NONE";
  }

  return MAP_COLORS[name] ?? "NONE";
}

